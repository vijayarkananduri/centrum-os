#!/bin/bash

################################################################################
#
# UI LIBRARY
# Terminal rendering and formatting utilities
#
################################################################################

# Color codes
COLOR_ORANGE='\033[38;2;255;102;0m'
COLOR_GREEN='\033[38;2;0;255;65m'
COLOR_DARK='\033[38;2;51;51;51m'
COLOR_BLUE='\033[38;2;0;136;255m'
COLOR_RESET='\033[0m'

################################################################################
# Banner
################################################################################

ui_banner() {
    echo -e "${COLOR_ORANGE}"
    echo "┌─────────────────────────────────────────┐"
    echo "│                                         │"
    echo "│      C E N T R U M   O S   v0.1        │"
    echo "│                                         │"
    echo "│      \"Return to focus.\"                 │"
    echo "│                                         │"
    echo "└─────────────────────────────────────────┘"
    echo -e "${COLOR_RESET}"
}

################################################################################
# Box
################################################################################

ui_box() {
    local content="$1"
    
    echo -e "${COLOR_ORANGE}┌─────────────────────────────────────────┐${COLOR_RESET}"
    while IFS= read -r line; do
        printf "${COLOR_ORANGE}│${COLOR_RESET} %-39s ${COLOR_ORANGE}│${COLOR_RESET}\n" "$line"
    done <<< "$content"
    echo -e "${COLOR_ORANGE}└─────────────────────────────────────────┘${COLOR_RESET}"
}

################################################################################
# Section header
################################################################################

ui_section() {
    local title="$1"
    echo -e "${COLOR_ORANGE}=== $title ===${COLOR_RESET}"
}

################################################################################
# Success message
################################################################################

ui_success() {
    local msg="$1"
    echo -e "${COLOR_GREEN}✓${COLOR_RESET} $msg"
}

################################################################################
# Error message
################################################################################

ui_error() {
    local msg="$1"
    echo -e "${COLOR_ORANGE}✗${COLOR_RESET} $msg" >&2
}

################################################################################
# Info message
################################################################################

ui_info() {
    local msg="$1"
    echo -e "${COLOR_BLUE}ℹ${COLOR_RESET} $msg"
}
